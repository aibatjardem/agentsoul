export const CLAUDE_MD_PATH = "CLAUDE.md"

const BEGIN = "<!-- agentsoul:begin — managed by `agentsoul update`, edits inside are overwritten -->"
const END = "<!-- agentsoul:end -->"
const BLOCK = /<!-- agentsoul:begin[^\n]*-->\n[\s\S]*?<!-- agentsoul:end -->\n?/

/** Soul files imported into every session, in load order. Local rules come last and win. */
export const BASELINE_IMPORTS = [".soul/identity.md", ".soul/agents.md", ".soul/stack.md", ".soul/glossary.md"]

/** The managed block: imports plus the session bootstrap rule. */
export function renderBlock(localFiles: readonly string[]): string {
    const imports = [...BASELINE_IMPORTS, ...[...localFiles].sort()].map((p) => `- @${p}`).join("\n")
    return `${BEGIN}
${imports}

## Session bootstrap — прочитать ПЕРВЫМ

Перед любой нетривиальной задачей проверь baseline:

1. \`.soul/stack.md\` содержит \`TBD\` → предложи запустить skill **\`project-initializer\`** и дождись его завершения, прежде чем писать код или архитектуру.
2. \`.soul/glossary.md\` содержит \`TBD\` → предложи skill **\`glossary-initializer\`**.

Можно работать и с пустым baseline: тривиальные правки одного файла, исследовательские вопросы, или пользователь явно сказал «делай быстро».

Правила из \`.soul/local/*.md\` сильнее всего остального. Карта skills и субагентов — в \`.soul/agents.md\`.
${END}
`
}

/**
 * Inserts or refreshes the managed block, preserving everything the user wrote around it.
 *
 * A file without a block (user-written, or generated by AgentSoul 0.1) gets the block
 * prepended, and stray `- @.soul/*.md` import lines outside it are removed so the
 * baseline is not loaded twice.
 */
export function upsertBlock(existing: string | null, localFiles: readonly string[]): string {
    const block = renderBlock(localFiles)
    if (existing === null || existing.trim() === "") return block
    if (BLOCK.test(existing)) return existing.replace(BLOCK, block)

    const rest = stripLegacy(existing)
    return rest.trim() === "" ? block : `${block}\n${rest.replace(/^\n+/, "")}`
}

/** True when the file carries a managed block. */
export function hasBlock(content: string): boolean {
    return BLOCK.test(content)
}

/** `@`-imports inside the managed block. */
export function blockImports(content: string): string[] {
    const block = BLOCK.exec(content)?.[0] ?? ""
    return [...block.matchAll(/^- @(\S+)$/gm)].map((m) => m[1] ?? "").filter((p) => p !== "")
}

/** Removes what AgentSoul 0.1 generated: bare soul imports and its bootstrap section. */
function stripLegacy(content: string): string {
    return content
        .replace(/^- @\.soul\/[a-z_-]+\.md\n/gm, "")
        .replace(/## ⚠ Session bootstrap — прочитать ПЕРВЫМ\n[\s\S]*?(?=\n---\n|\n## |$)/, "")
        .replace(/^Полный индекс субагентов и правила вызова — в `\.soul\/agents\.md`\.\n?/m, "")
        .replace(/^\n*---\n/, "")
}
